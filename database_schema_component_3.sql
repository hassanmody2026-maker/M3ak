-- ============================================================
-- M3AK - Component 3
-- Monthly AI Quotas, Durable Reservations, Atomic Settlement
-- and Recovery Support
--
-- Additive migration.
-- Keeps existing users counters and all existing application data.
-- PostgreSQL
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. Persistent monthly quota anchor on users
-- ------------------------------------------------------------

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS ai_quota_anchor_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS ai_quota_anchor_day SMALLINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'users_ai_quota_anchor_day_check'
    ) THEN
        ALTER TABLE users
        ADD CONSTRAINT users_ai_quota_anchor_day_check
        CHECK (
            ai_quota_anchor_day IS NULL
            OR ai_quota_anchor_day BETWEEN 1 AND 31
        );
    END IF;
END
$$;


-- ------------------------------------------------------------
-- 2. Monthly quota periods
-- Each user has one row per quota period.
-- Limits are snapshots and must not change retroactively.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_quota_periods (
    id BIGSERIAL PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,

    anchor_day SMALLINT NOT NULL
        CHECK (anchor_day BETWEEN 1 AND 31),

    words_limit BIGINT NOT NULL
        CHECK (words_limit >= 0),

    images_limit BIGINT NOT NULL
        CHECK (images_limit >= 0),

    words_consumed BIGINT NOT NULL DEFAULT 0
        CHECK (words_consumed >= 0),

    images_consumed BIGINT NOT NULL DEFAULT 0
        CHECK (images_consumed >= 0),

    words_reserved BIGINT NOT NULL DEFAULT 0
        CHECK (words_reserved >= 0),

    images_reserved BIGINT NOT NULL DEFAULT 0
        CHECK (images_reserved >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ai_quota_period_valid_range
        CHECK (period_end > period_start),

    CONSTRAINT ai_quota_period_user_start_unique
        UNIQUE (user_id, period_start),

    CONSTRAINT ai_quota_period_id_user_unique
        UNIQUE (id, user_id),

    CONSTRAINT ai_quota_words_within_limit
        CHECK (words_consumed + words_reserved <= words_limit),

    CONSTRAINT ai_quota_images_within_limit
        CHECK (images_consumed + images_reserved <= images_limit)
);


-- ------------------------------------------------------------
-- 3. Durable AI request reservations
--
-- reservation_id is generated by the application.
-- No database extension is required.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_request_reservations (
    reservation_id UUID PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    period_id BIGINT NOT NULL,

    idempotency_key VARCHAR(200) NOT NULL,

    reserved_words BIGINT NOT NULL DEFAULT 0
        CHECK (reserved_words >= 0),

    reserved_images BIGINT NOT NULL DEFAULT 0
        CHECK (reserved_images >= 0),

    actual_words BIGINT
        CHECK (actual_words IS NULL OR actual_words >= 0),

    actual_images BIGINT
        CHECK (actual_images IS NULL OR actual_images >= 0),

    status VARCHAR(30) NOT NULL DEFAULT 'reserved'
        CHECK (
            status IN (
                'reserved',
                'provider_succeeded',
                'settled',
                'refunded',
                'unknown',
                'failed'
            )
        ),

    provider_request_id VARCHAR(255),
    provider_succeeded_at TIMESTAMPTZ,

    lease_expires_at TIMESTAMPTZ NOT NULL,

    last_error TEXT,

    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ai_reservation_user_idempotency_unique
        UNIQUE (user_id, idempotency_key),

    CONSTRAINT ai_reservation_period_user_fk
        FOREIGN KEY (period_id, user_id)
        REFERENCES ai_quota_periods(id, user_id)
        ON DELETE RESTRICT
);


-- ------------------------------------------------------------
-- 4. Immutable usage event ledger
--
-- Each logical operation must have a unique event_key.
-- Application code must insert ledger events and update quota
-- counters in the same database transaction.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_usage_ledger (
    id BIGSERIAL PRIMARY KEY,

    event_key VARCHAR(255) NOT NULL UNIQUE,

    reservation_id UUID NOT NULL
        REFERENCES ai_request_reservations(reservation_id)
        ON DELETE RESTRICT,

    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    period_id BIGINT NOT NULL,

    event_type VARCHAR(30) NOT NULL
        CHECK (
            event_type IN (
                'reserve',
                'settle',
                'refund',
                'recovery_adjustment'
            )
        ),

    words_delta BIGINT NOT NULL DEFAULT 0,
    images_delta BIGINT NOT NULL DEFAULT 0,

    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ai_ledger_period_user_fk
        FOREIGN KEY (period_id, user_id)
        REFERENCES ai_quota_periods(id, user_id)
        ON DELETE RESTRICT
);


-- ------------------------------------------------------------
-- 5. Recovery jobs
--
-- A worker can claim expired reservations safely using
-- FOR UPDATE SKIP LOCKED.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_recovery_jobs (
    id BIGSERIAL PRIMARY KEY,

    reservation_id UUID NOT NULL UNIQUE
        REFERENCES ai_request_reservations(reservation_id)
        ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'processing',
                'completed',
                'failed'
            )
        ),

    attempts INTEGER NOT NULL DEFAULT 0
        CHECK (attempts >= 0),

    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    locked_at TIMESTAMPTZ,
    locked_by VARCHAR(150),

    last_error TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ------------------------------------------------------------
-- 6. Indexes
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_ai_quota_periods_user_range
    ON ai_quota_periods(user_id, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_ai_reservations_user_created
    ON ai_request_reservations(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ai_reservations_status_lease
    ON ai_request_reservations(status, lease_expires_at);

CREATE INDEX IF NOT EXISTS idx_ai_reservations_period
    ON ai_request_reservations(period_id, user_id);

CREATE INDEX IF NOT EXISTS idx_ai_ledger_user_created
    ON ai_usage_ledger(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ai_ledger_reservation
    ON ai_usage_ledger(reservation_id);

CREATE INDEX IF NOT EXISTS idx_ai_recovery_jobs_due
    ON ai_recovery_jobs(status, next_attempt_at);

CREATE INDEX IF NOT EXISTS idx_ai_recovery_jobs_locked
    ON ai_recovery_jobs(status, locked_at);


-- ------------------------------------------------------------
-- 7. Documentation
-- ------------------------------------------------------------

COMMENT ON TABLE ai_quota_periods IS
'Monthly AI quota periods. Limits are immutable snapshots for each period.';

COMMENT ON TABLE ai_request_reservations IS
'Durable idempotent AI request reservations and provider execution state.';

COMMENT ON TABLE ai_usage_ledger IS
'Idempotent accounting events for AI quota reservations, settlements and refunds.';

COMMENT ON TABLE ai_recovery_jobs IS
'Retryable recovery tasks for expired or uncertain AI reservations.';

COMMENT ON COLUMN users.ai_quota_anchor_at IS
'Persisted timestamp defining the users monthly AI quota billing anchor.';

COMMENT ON COLUMN users.ai_quota_anchor_day IS
'Original monthly anchor day, from 1 to 31. Short months must be handled by application date logic.';

COMMIT;
